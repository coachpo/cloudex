const dictionaries = { en, "zh-CN": zhCN };
export const interpolation = /\{(\w+)\}/g;

export function resolveLocale(acceptLanguage: string | null): Locale {
  const preferences = (acceptLanguage ?? "").split(",").map((entry) => {
    const [tag, ...params] = entry.toLowerCase().split(";").map((part) => part.trim());
    const weight = params.find((part) => /^q\s*=/.test(part));
    return { tag, quality: weight === undefined ? 1 : Number(weight.split("=")[1]) };
  }).filter(({ quality }) => quality > 0 && quality <= 1);
  for (const { tag } of preferences.sort((a, b) => b.quality - a.quality)) {
    if (tag.startsWith("zh")) return "zh-CN";
    if (tag.startsWith("en")) return "en";
  }
  return "en";
}

export function message(locale: Locale, key: MessageKey, values?: Record<string, string | number>): string {
  const text = dictionaries[locale][key];
  return values ? text.replace(interpolation, (placeholder, name: string) => values[name]?.toString() ?? placeholder) : text;
}

export type Translate = (key: MessageKey, values?: Record<string, string | number>) => string;

export function hasMessage(key: string): key is MessageKey {
  return Object.hasOwn(en, key);
}

export function statusName(t: Translate, state: string): string {
  const key = `state.${state}`;
  return hasMessage(key) ? t(key) : state ? state[0].toUpperCase() + state.slice(1) : t("unknown");
}

export function hostName(t: Translate, host: { id: string; name: string }): string {
  return host.id === "local" && host.name === en.localHost ? t("localHost") : host.name;
}

const knownOriginals = new Map(
  (Object.keys(en) as MessageKey[])
    .filter((key) => key.startsWith("validation.") || key.startsWith("sshMessage."))
    .map((key) => [en[key], key]),
);

export function localizeSSHMessage(locale: Locale, original: string): string {
  if (original === en["error.WORKSPACE_PAUSED"]) return message(locale, "error.WORKSPACE_PAUSED");
  const key = knownOriginals.get(original);
  return key?.startsWith("sshMessage.") ? message(locale, key) : original;
}

export function localizeProblem(locale: Locale, code: string | undefined, original: string): string {
  if (locale === "en") return original;
  if (code === "INVALID_REQUEST" || code === "INVALID_CODEX_CONFIG") {
    const key = knownOriginals.get(original);
    return key?.startsWith("validation.") ? message(locale, key) : original;
  }
  if (code === "WORKSPACE_BUSY" && original === en.workspaceNotRunning) return message(locale, "workspaceNotRunning");
  if (code === "INSUFFICIENT_HOST_CAPACITY") {
    const resource = /(?:Not|not) enough (cpu|memory|disk) capacity/.exec(original)?.[1];
    const resources = { cpu: "cpuCores", memory: "memory", disk: "disk" } as const;
    if (resource === "cpu" || resource === "memory" || resource === "disk") {
      return message(locale, "capacityResourceError",
        { resource: message(locale, resources[resource]) });
    }
  }
  const key = `error.${code}`;
  return hasMessage(key) ? message(locale, key) : original;
}
